require('module-alias/register');
const {
  generateReportCards,
  generatePDFReportCard,
  getReportCardAttendance
} = require('../src/controllers/academic/exam-reports/exam-reports.controller');
const { ReportCardSetup, Student, AttendanceRecord } = require('../src/models');

describe('weighted report-card generation access', () => {
  const originalFindOne = ReportCardSetup.findOne;
  const originalStudentFindAll = Student.findAll;
  const originalAttendanceFindAll = AttendanceRecord.findAll;
  const request = branchId => ({
    body: { setup_id: 'setup-1', student_ids: ['student-1'] },
    user: { school_id: 'school-1' },
    schoolId: 'school-1',
    branchId
  });
  const response = () => ({ status: jest.fn().mockReturnThis(), json: jest.fn() });

  afterEach(() => {
    ReportCardSetup.findOne = originalFindOne;
    Student.findAll = originalStudentFindAll;
    AttendanceRecord.findAll = originalAttendanceFindAll;
  });

  test('requires one explicit branch before looking up a setup', async () => {
    ReportCardSetup.findOne = jest.fn();
    const res = response();

    await generateReportCards(request(undefined), res);

    expect(res.status).toHaveBeenCalledWith(400);
    expect(ReportCardSetup.findOne).not.toHaveBeenCalled();
  });

  test('does not let teachers request Student 360 archive writes', async () => {
    ReportCardSetup.findOne = jest.fn();
    const req = request('branch-1');
    req.user.role = 'teacher';
    req.body.archive_report_cards = true;
    const res = response();

    await generateReportCards(req, res);

    expect(res.status).toHaveBeenCalledWith(403);
    expect(ReportCardSetup.findOne).not.toHaveBeenCalled();
  });

  test('refuses generation while the setup or any included exam is unreleased', async () => {
    ReportCardSetup.findOne = jest.fn().mockResolvedValue({
      is_published: true,
      template: { is_active: true, report_type: 'student_wise' },
      examEntries: [{ exam_id: 'exam-1', exam: { result_status: false } }]
    });
    Student.findAll = jest.fn();
    const res = response();

    await generateReportCards(request('branch-1'), res);

    expect(res.status).toHaveBeenCalledWith(409);
    expect(Student.findAll).not.toHaveBeenCalled();
  });

  test('rejects a mixed-branch or missing student selection instead of generating a partial report', async () => {
    ReportCardSetup.findOne = jest.fn().mockResolvedValue({
      id: 'setup-1',
      school_id: 'school-1',
      branch_id: 'branch-1',
      is_published: true,
      template: { is_active: true, report_type: 'student_wise', school_id: null },
      examEntries: [{
        exam_id: 'exam-1',
        exam: {
          id: 'exam-1',
          name: 'First Term',
          school_id: 'school-1',
          branch_id: 'branch-1',
          is_active: true,
          result_status: true,
          toJSON: () => ({ id: 'exam-1', name: 'First Term', school_id: 'school-1', branch_id: 'branch-1' })
        }
      }]
    });
    Student.findAll = jest.fn().mockResolvedValue([]);
    AttendanceRecord.findAll = jest.fn();
    const res = response();

    await generateReportCards(request('branch-1'), res);

    expect(res.status).toHaveBeenCalledWith(404);
    expect(res.json).toHaveBeenCalledWith({
      success: false,
      message: 'One or more selected students were not found'
    });
    expect(Student.findAll.mock.calls[0][0].where).toEqual({
      id: expect.any(Object),
      school_id: 'school-1',
      branch_id: 'branch-1'
    });
    expect(AttendanceRecord.findAll).not.toHaveBeenCalled();
  });

  test('renders a readable weighted PDF with the configured template and exam breakdown', async () => {
    const pdf = await generatePDFReportCard(
      {
        name: 'Annual Report',
        school: { name: 'Demo International School' },
        branch: { name: 'Main Branch' }
      },
      [
        {
          id: 'student-1',
          first_name: 'Sarah',
          last_name: 'Demo',
          admission_number: 'DEMO-001',
          roll_number: '1',
          class: { name: 'Class 1' }
        }
      ],
      {
        'student-1': {
          percentage: 83,
          grade: 'A',
          exam_breakdown: [
            {
              exam_name: 'First Term Examination',
              weightage: 50,
              percentage: 86,
              has_result: true
            },
            {
              exam_name: 'Second Term Examination',
              weightage: 50,
              percentage: 80,
              has_result: true
            }
          ]
        }
      },
      null,
      {
        name: 'Demo Student Report Card',
        footer_template: '<p>Generated by School ERP</p>',
        config: { show_remarks: true }
      }
    );

    expect(pdf.subarray(0, 5).toString()).toBe('%PDF-');
    expect(pdf.length).toBeGreaterThan(1000);
  });

  test('counts late students as attended in weighted report-card summaries', async () => {
    AttendanceRecord.findAll = jest.fn().mockResolvedValue([
      { student_id: 'student-1', status: 'present', record_count: 8 },
      { student_id: 'student-1', status: 'late', record_count: 1 },
      { student_id: 'student-1', status: 'absent', record_count: 3 }
    ]);

    const summary = await getReportCardAttendance(['student-1'], 'school-1', 'branch-1', '2026-2027');

    expect(summary['student-1']).toEqual({ total: 12, present: 8, late: 1 });
  });
});
